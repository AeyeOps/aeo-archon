# Ensure Supabase via Supabase CLI (npx) and populate .env. Fail fast if unavailable.
ensure_supabase_env(){
  command -v npx >/dev/null 2>&1 || { err "npx not found. Install Node.js (>=18) to use supabase CLI"; exit 1; }
  mkdir -p "$SUPABASE_DIR"
  pushd "$SUPABASE_DIR" >/dev/null

  # Check for version drift (warn if CLI version changed)
  if type -t check_version_drift >/dev/null 2>&1; then
    check_version_drift || true  # Continue even if drift detected
  fi

  # Pre-start cleanup to prevent container name conflicts
  if type -t cleanup_stale_containers >/dev/null 2>&1; then
    cleanup_stale_containers
  fi

  # Supabase CLI keeps config under ./supabase/config.toml
  if [[ ! -f "supabase/config.toml" ]]; then
    npx -y supabase@${SUPABASE_VERSION:-2.70.5} init || { err "Failed to initialize Supabase CLI project"; exit 1; }
  fi

  # Attempt to start Supabase, with automatic recovery for storage migration issues
  local start_attempts=${SUPABASE_START_ATTEMPTS:-1}
  local debug_flag=""
  [[ ${SUPABASE_DEBUG:-0} -eq 1 ]] && debug_flag="--debug"
  for attempt in $(seq 1 $start_attempts); do
    if npx -y supabase@${SUPABASE_VERSION:-2.70.5} start $debug_flag; then
      break
    else
      if [[ $attempt -lt $start_attempts ]]; then
        warn "Supabase start failed (attempt $attempt/$start_attempts). Attempting recovery..."
        # Check if storage container failed
        if docker logs supabase_storage_supabase 2>&1 | grep -q "duplicate key value violates unique constraint"; then
          warn "Storage migration conflict detected - resetting migrations and cleaning old images..."
          if type -t recover_storage_migrations >/dev/null 2>&1; then
            recover_storage_migrations
          else
            # Inline recovery if function not available
            docker exec supabase_db_supabase bash -c \
              'PGPASSWORD=postgres psql -U supabase_admin -d postgres -c "TRUNCATE storage.migrations RESTART IDENTITY CASCADE;"' 2>/dev/null || true
          fi
          # Clean old storage-api images to ensure CLI pulls correct version
          if type -t cleanup_old_supabase_images >/dev/null 2>&1; then
            cleanup_old_supabase_images
          fi
        fi
        # Clean up and retry
        npx -y supabase@${SUPABASE_VERSION:-2.70.5} stop 2>/dev/null || true
        if type -t cleanup_stale_containers >/dev/null 2>&1; then
          cleanup_stale_containers
        fi
      else
        err "Failed to start local Supabase via CLI after $start_attempts attempts"
        exit 1
      fi
    fi
  done

  # Verify port bindings - fail fast if containers started without host bindings
  # This can happen when Docker restarts containers (via restart policy) without
  # going through the Supabase CLI, which manages port mappings
  if type -t verify_supabase_port_bindings >/dev/null 2>&1; then
    if ! verify_supabase_port_bindings; then
      if [[ $no_port_check -eq 1 ]]; then
        warn "Port bindings missing - continuing anyway (--no-port-check)"
      else
        warn "Port bindings missing - attempting recovery restart..."
        npx -y supabase@${SUPABASE_VERSION:-2.70.5} stop
        npx -y supabase@${SUPABASE_VERSION:-2.70.5} start

        # Second check - fail hard if still broken
        if ! verify_supabase_port_bindings; then
          err "FATAL: Supabase port bindings failed after recovery restart"
          err "External apps will NOT be able to connect to Supabase"
          err "Use --no-port-check to continue anyway for debugging"
          err "Try: npx supabase@${SUPABASE_VERSION:-2.70.5} stop && npx supabase@${SUPABASE_VERSION:-2.70.5} start"
          exit 1
        fi
      fi
    fi
  fi

  # Enforce shm_size on Postgres container (Supabase CLI ignores Docker daemon defaults)
  # Native Docker may require root; Docker Desktop can recreate as non-root
  if type -t enforce_postgres_shm_size >/dev/null 2>&1; then
    local desired_shm_bytes
    desired_shm_bytes="${POSTGRES_SHM_SIZE_BYTES:-4294967296}"
    if ! enforce_postgres_shm_size supabase_db_supabase "$desired_shm_bytes"; then
      if [[ $EUID -ne 0 ]]; then
        # Attempt non-interactive sudo (avoid hanging on password prompt)
        if command -v sudo >/dev/null 2>&1; then
          sudo -n bash -lc "source \"$ROOT_DIR/lib/supabase-utils.sh\" && enforce_postgres_shm_size supabase_db_supabase \"$desired_shm_bytes\"" || true
        fi
      fi
    fi

    # Fail fast if shm_size is still too small
    local current_shm
    current_shm=$(docker inspect -f '{{.HostConfig.ShmSize}}' supabase_db_supabase 2>/dev/null || echo "0")
    if [[ "$current_shm" -lt "$desired_shm_bytes" ]]; then
      err "Postgres shm_size is $(numfmt --to=iec "$current_shm" 2>/dev/null || echo "${current_shm} bytes") (required: $(numfmt --to=iec "$desired_shm_bytes" 2>/dev/null || echo "${desired_shm_bytes} bytes"))"
      docker_os=$(docker info -f '{{.OperatingSystem}}' 2>/dev/null || true)
      if [[ "$docker_os" == *"Docker Desktop"* ]]; then
        err "Docker Desktop detected: shm_size enforcement failed. Check bootstrap logs for container recreation errors."
      else
        err "Run bootstrap-archon.sh with sudo (so shm_size can be enforced)."
      fi
      exit 1
    fi
  fi

  # Query status in env format and parse required values
  STATUS_ENV=$(npx -y supabase@${SUPABASE_VERSION:-2.70.5} status -o env) || { err "Failed to get Supabase status"; exit 1; }
  SERVICE_ROLE_KEY=$(echo "$STATUS_ENV" | awk -F'=' '/^SERVICE_ROLE_KEY/{gsub(/"/,"",$2); print $2}')
  API_URL=$(echo "$STATUS_ENV" | awk -F'=' '/^API_URL/{gsub(/"/,"",$2); print $2}')
  popd >/dev/null
  if [[ -z "$SERVICE_ROLE_KEY" || -z "$API_URL" ]]; then
    err "Supabase status missing SERVICE_ROLE_KEY or API_URL; cannot continue"; exit 1
  fi
  upsert_env SUPABASE_URL "$API_URL"
  SUPABASE_KONG=$(docker ps --format '{{.Names}}' | grep -m1 'supabase_kong' || true)
  if [[ -n "$SUPABASE_KONG" ]]; then
    # Resolve container name to IP for upstream URL validation compatibility
    # (upstream rejects container hostnames but accepts RFC 1918 private IPs)
    KONG_IP=$(docker inspect "$SUPABASE_KONG" --format '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}' 2>/dev/null | head -1)
    if [[ -n "$KONG_IP" ]]; then
      upsert_env SUPABASE_URL_CONTAINER "http://${KONG_IP}:8000"
    else
      # Fallback to container name - will likely fail upstream URL validation
      warn "Could not resolve Kong container IP. Server may fail to start."
      upsert_env SUPABASE_URL_CONTAINER "http://$SUPABASE_KONG:8000"
    fi
    wait_for_supabase_ready "$SUPABASE_KONG"
  else
    upsert_env SUPABASE_URL_CONTAINER "http://host.docker.internal:54321"
  fi
  upsert_env SUPABASE_SERVICE_KEY "$SERVICE_ROLE_KEY"

  # Record successful version for future drift detection
  if type -t record_supabase_version >/dev/null 2>&1; then
    record_supabase_version
  fi

  ok "Supabase configured via supabase CLI"
}

