upsert_src_env HOST "$(grep -E '^HOST=' "$ENV_FILE" | sed 's/^HOST=//')"
upsert_src_env ARCHON_SERVER_PORT "$(grep -E '^ARCHON_SERVER_PORT=' "$ENV_FILE" | sed 's/^ARCHON_SERVER_PORT=//')"
