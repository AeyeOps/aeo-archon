    if [[ -f "$ARCHON_SRC_ENV" ]]; then
      upsert_env_file "$ARCHON_SRC_ENV" OTEL_EXPORTER_OTLP_HEADERS "$DESIRED_HEADERS_QUOTED"
    fi
  fi
fi

