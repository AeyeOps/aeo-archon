  if type -t auto_backup >/dev/null 2>&1; then
    auto_backup "pre-fresh"
  fi
fi

# Run database migrations (idempotent, optional) before starting services
if [[ $run_migrations -eq 1 ]]; then
  echo "Running database migrations..."

  # Copy fresh migration files from archon-src
  if [[ -d "$ARCHON_SRC_DIR/migration" ]]; then
    echo "Copying migration files from archon-src..."
    # Copy root-level SQL files
    cp -f "$ARCHON_SRC_DIR/migration"/*.sql "$ROOT_DIR/migration/" 2>/dev/null || true
    # Copy all versioned subdirectories (0.1.0, 0.2.0, etc.)
    for subdir in "$ARCHON_SRC_DIR/migration"/*/; do
      if [[ -d "$subdir" ]]; then
        subdir_name=$(basename "$subdir")
        mkdir -p "$ROOT_DIR/migration/$subdir_name"
        cp -f "$subdir"*.sql "$ROOT_DIR/migration/$subdir_name/" 2>/dev/null || true
      fi
