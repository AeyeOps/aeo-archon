upsert_src_env(){ local k="$1"; local v="$2"; local tmp="$SRC_ENV.tmp"; awk -v k="$k" -v v="$v" 'BEGIN{done=0}{ if(!done && $0 ~ "^" k "=") { print k"="v; done=1 } else { print $0 } } END{ if(!done) print k"="v }' "$SRC_ENV" > "$tmp"; mv "$tmp" "$SRC_ENV"; }
